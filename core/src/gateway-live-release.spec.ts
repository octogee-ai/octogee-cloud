const POD_NAME = "octogee-gateway-walter-5bc5949d46-p946t";

describe("podBelongsToGateway", () => {
  it("accepts pods generated by the gateway's stable-name Deployment", () => {
    expect(podBelongsToGateway("walter", POD_NAME)).toBe(true);
  });

  it("rejects another gateway's pods, a bare deployment name, and junk suffixes", () => {
    expect(podBelongsToGateway("walter", "octogee-gateway-other-5bc5949d46-p946t")).toBe(false);
    expect(podBelongsToGateway("walter", "octogee-gateway-walter")).toBe(false);
    expect(podBelongsToGateway("walter", "octogee-gateway-walter-")).toBe(false);
    expect(podBelongsToGateway("walter", "octogee-gateway-walter-UPPER")).toBe(false);
    expect(podBelongsToGateway("walter", undefined)).toBe(false);
  });
});

describe("configuredUserBootstrapAllowed", () => {
  const configured = {
    gatewayId: "walter",
    createdAt: 1,
    createdBy: "admin",
    updatedAt: 1,
    updatedBy: "admin",
    latestRelease: 2,
    desiredRelease: 2,
    liveRelease: 1,
    desiredStatus: "running",
    ...mutableConfig({ builderSlug: "alice" }),
  };

  it("allows the configured isolated user while the gateway is running", () => {
    expect(configuredUserBootstrapAllowed(configured, {
      gatewayId: "walter",
      podName: POD_NAME,
      slug: "alice",
    })).toBe(true);
    expect(configuredUserBootstrapAllowed(configured, {
      gatewayId: "walter",
      podName: POD_NAME,
      slug: "victim",
    })).toBe(false);
    expect(configuredUserBootstrapAllowed({ ...configured, gatewayId: "other" }, {
      gatewayId: "walter",
      podName: POD_NAME,
      slug: "alice",
    })).toBe(false);
    expect(configuredUserBootstrapAllowed(configured, {
      gatewayId: "walter",
      podName: "octogee-gateway-other-5bc5949d46-p946t",
      slug: "alice",
    })).toBe(false);
  });

  it.each([
    { desiredStatus: "paused" },
    { desiredStatus: "draining" },
    { desiredStatus: "retired" },
    { retireAfter: 2 },
    { retirementClaim: { operationId: "retire-1", version: 1 } },
  ])("rejects configured-user bootstrap after lifecycle revocation: %o", (override) => {
    expect(configuredUserBootstrapAllowed({ ...configured, ...override }, {
      gatewayId: "walter",
      podName: POD_NAME,
      slug: "alice",
    })).toBe(false);
  });

  it("rejects shared gateways because they have no configured user identity", () => {
    expect(configuredUserBootstrapAllowed({ ...configured, gatewayClass: "shared" }, {
      gatewayId: "walter",
      podName: POD_NAME,
      slug: "alice",
    })).toBe(false);
  });
});

describe("configuredUserCredentialBootstrapAllowed", () => {
  const configured = {
    gatewayId: "walter",
    createdAt: 1,
    createdBy: "admin",
    updatedAt: 1,
    updatedBy: "admin",
    latestRelease: 2,
    desiredRelease: 2,
    liveRelease: 1,
    desiredStatus: "running",
    ...mutableConfig({ builderSlug: "alice", ownerUid: "uid-alice" }),
  };

  it("allows credentials for the configured user owner while the gateway is running", () => {
    expect(configuredUserCredentialBootstrapAllowed(configured, {
      gatewayId: "walter",
      podName: POD_NAME,
      slug: "alice",
      uid: "uid-alice",
    })).toBe(true);
    expect(configuredUserCredentialBootstrapAllowed(configured, {
      gatewayId: "walter",
      podName: POD_NAME,
      slug: "alice",
      uid: "uid-victim",
    })).toBe(false);
  });

  it.each([
    { desiredStatus: "paused" },
    { desiredStatus: "draining" },
    { desiredStatus: "retired" },
    { retireAfter: 2 },
    { retirementClaim: { operationId: "retire-1", version: 1 } },
  ])("rejects credential bootstrap after lifecycle revocation: %o", (override) => {
    expect(configuredUserCredentialBootstrapAllowed({ ...configured, ...override }, {
      gatewayId: "walter",
      podName: POD_NAME,
      slug: "alice",
      uid: "uid-alice",
    })).toBe(false);
  });

  it("rejects cross-tenant configured-user identity", () => {
    expect(configuredUserCredentialBootstrapAllowed(configured, {
      gatewayId: "walter",
      podName: POD_NAME,
      slug: "victim",
      uid: "uid-alice",
    })).toBe(false);
    expect(configuredUserCredentialBootstrapAllowed(configured, {
      gatewayId: "other",
      podName: POD_NAME,
      slug: "alice",
      uid: "uid-alice",
    })).toBe(false);
  });
});

type Docs = Record<string, Record<string, unknown>>;

function mutableConfig(
  overrides: Partial<GatewayMutableConfig> = {},
): GatewayMutableConfig {
  return {
    configSchemaVersion: 1,
    profile: "isolated",
    gatewayClass: "isolated",
    imageProfile: "isolated",
    sizingTier: "l",
    gcpProject: null,
    gatewayContainerSecurityContext: null,
    serviceAccountName: null,
    serviceAccount: null,
    builderAccess: { controlUiEnabled: true },
    ownerUid: "uid-ceckert",
    builderSlug: "ceckert",
    modelBrokerLimits: null,
    preemption: null,
    ...overrides,
  };
}

function durableGateway(overrides: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    gatewayId: "walter",
    latestRelease: 2,
    desiredRelease: 2,
    liveRelease: 2,
    desiredStatus: "running",
    ...mutableConfig(),
    ...overrides,
  };
}

function servingRuntime(overrides: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    docKind: "runtime",
    gatewayId: "walter",
    release: 2,
    lifecycle: "serving",
    heartbeat: { status: "ready" },
    ...overrides,
  };
}

describe("initialGatewayReleaseDocuments", () => {
  it("materializes one durable root and its immutable first release", () => {
    const config = mutableConfig({
      profile: null,
      gatewayClass: "shared",
      imageProfile: "standard",
      sizingTier: null,
      builderAccess: null,
      ownerUid: null,
      builderSlug: null,
    });
    const result = initialGatewayReleaseDocuments({
      gatewayId: "default",
      config,
      artifact: {
        imageRepository: "us-west1-docker.pkg.dev/octogee/octogee/octogee-gateway",
        imageTag: "753c212",
      },
      createdBy: "glm-controller-bootstrap",
      now: 42,
      desiredStatus: "running",
    });

    expect(result.gatewayDoc).toMatchObject({
      gatewayId: "default",
      latestRelease: 1,
      desiredRelease: 1,
      liveRelease: null,
      desiredStatus: "running",
      gatewayClass: "shared",
    });
    expect(result.releaseDoc).toMatchObject({
      gatewayId: "default",
      release: 1,
      sourceRelease: null,
      payload: {
        imageRepository: "us-west1-docker.pkg.dev/octogee/octogee/octogee-gateway",
        imageTag: "753c212",
      },
    });
    expect(result.releaseDoc.payloadHash).toBe(
      releasePayloadHash(result.releaseDoc.payload),
    );
  });
});

describe("gateway durable configuration authorization", () => {
  it("authorizes a durable root document without issuing a second Firestore read", () => {
    expect(gatewayAuthorizationFromRootDocument(durableGateway(), "walter")).toMatchObject({
      kind: "durable",
      gateway: { gatewayId: "walter" },
      config: { ownerUid: "uid-ceckert" },
    });
    expect(gatewayAuthorizationFromRootDocument(durableGateway(), "other")).toBeNull();
  });

  it("authorizes an empty retired co-owner mirror without exposing it as mutable config", () => {
    const authorization = gatewayAuthorizationFromRootDocument(
      durableGateway({ coOwnerUids: [] }),
      "walter",
    );

    expect(authorization).toMatchObject({
      kind: "durable",
      gateway: { gatewayId: "walter" },
      config: { ownerUid: "uid-ceckert" },
    });
    expect(authorization?.config).not.toHaveProperty("coOwnerUids");
    expect(
      gatewayAuthorizationFromRootDocument(
        durableGateway({ coOwnerUids: ["uid-former-helper"] }),
        "walter",
      ),
    ).toBeNull();
  });

  it("rejects revision-shaped ids before attempting a durable root read", async () => {
    let reads = 0;
    const state = {
      gateways: {
        roots: {
          get() {
            reads += 1;
            throw new Error("revision ids must not reach the store");
          },
        },
      },
    };

    expect(isBareGatewayId("walter")).toBe(true);
    expect(isBareGatewayId("walter-r2")).toBe(false);
    await expect(readGatewayAuthorizationInStore(state as never, "walter-r2")).resolves.toBeNull();
    expect(reads).toBe(0);
  });

  it("uses root mutable configuration instead of stale bare glm gateway config", async () => {
    const docs: Docs = {
      "gateways/walter": durableGateway(),
      "gateways/walter/releases/2": {
        gatewayId: "walter",
        release: 2,
        payload: {
          gatewayClass: "shared",
          ownerUid: "uid-someone-else",
          builderAccess: { controlUiEnabled: false },
        },
      },
      "glmGateways/walter": servingRuntime(),
    };

    await expect(readGatewayAuthorizationInStore(createDocumentFixtureStore(docs), "walter")).resolves.toMatchObject({
      kind: "durable",
      config: {
        gatewayClass: "isolated",
        ownerUid: "uid-ceckert",
        builderAccess: { controlUiEnabled: true },
      },
    });
    await expect(readServingGatewayAuthorization(createDocumentFixtureStore(docs), "walter")).resolves.toMatchObject({
      kind: "durable",
      config: { gatewayClass: "isolated" },
    });
  });

  it("fails closed when the runtime doc is legacy-shaped instead of a runtime record", async () => {
    const docs: Docs = {
      "gateways/walter": durableGateway(),
      "glmGateways/walter": {
        gatewayId: "walter",
        ownerUid: "uid-ceckert",
        gatewayClass: "shared",
        profile: "standard",
      },
    };
    await expect(readServingGatewayAuthorization(createDocumentFixtureStore(docs), "walter")).resolves.toBeNull();
  });

  it("fails closed instead of falling back to stale bare glm config before the root config marker exists", async () => {
    const docs: Docs = {
      "gateways/walter": durableGateway({ configSchemaVersion: undefined }),
      "glmGateways/walter": {
        gatewayId: "walter",
        ownerUid: "uid-ceckert",
        gatewayClass: "isolated",
      },
    };

    await expect(readGatewayAuthorizationInStore(createDocumentFixtureStore(docs), "walter")).resolves.toBeNull();
  });

  it("fails closed when no durable gateway exists instead of reading a bare glm config", async () => {
    const docs: Docs = {
      "glmGateways/walter": {
        gatewayId: "walter",
        ownerUid: "uid-ceckert",
        gatewayClass: "isolated",
        builderAccess: { controlUiEnabled: true },
      },
    };

    await expect(readServingGatewayAuthorization(createDocumentFixtureStore(docs), "walter")).resolves.toBeNull();
  });

  it("does not authorize a runtime realization without a durable root", async () => {
    const docs: Docs = {
      "glmGateways/walter": servingRuntime({
        ownerUid: "uid-ceckert",
        gatewayClass: "isolated",
      }),
    };

    await expect(readGatewayAuthorizationInStore(createDocumentFixtureStore(docs), "walter")).resolves.toBeNull();
  });

  it("refuses a malformed durable gateway doc instead of reviving stale legacy authority", async () => {
    const docs: Docs = {
      "gateways/walter": { gatewayId: "walter", desiredStatus: "running" },
      "glmGateways/walter": {
        gatewayId: "walter",
        ownerUid: "uid-ceckert",
        gatewayClass: "isolated",
        builderAccess: { controlUiEnabled: true },
      },
    };

    await expect(readGatewayAuthorizationInStore(createDocumentFixtureStore(docs), "walter")).rejects.toBeInstanceOf(
      MalformedRecordError,
    );
  });

  it("rejects a runtime realization that is missing or not serving", async () => {
    const docs: Docs = {
      "gateways/walter": durableGateway(),
      "glmGateways/walter": servingRuntime({ lifecycle: "failed" }),
    };

    await expect(readServingGatewayAuthorization(createDocumentFixtureStore(docs), "walter")).resolves.toBeNull();
    await expect(
      readServingGatewayAuthorization(createDocumentFixtureStore({ "gateways/walter": durableGateway() }), "walter"),
    ).resolves.toBeNull();
  });

  it("merges only root mutable configuration with the selected immutable artifact", () => {
    const config = {
      ...mutableConfig(),
      imageTag: "stale-tag",
    } as unknown as GatewayMutableConfig;

    const rendered = mergeGatewayConfigWithArtifact(config, {
      imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
      imageTag: "deadbee",
    });

    expect(rendered).toMatchObject({
      imageTag: "deadbee",
      gatewayClass: "isolated",
      ownerUid: "uid-ceckert",
    });
    expect(rendered).not.toHaveProperty("configSchemaVersion");
  });

  it("rejects invalid mutable ownership and preemption values", () => {
    expect(isGatewayMutableConfig(mutableConfig({ ownerUid: null }))).toBe(false);
    expect(isGatewayMutableConfig({ ...mutableConfig(), coOwnerUids: [""] })).toBe(false);
    expect(
      isGatewayMutableConfig(mutableConfig({ modelBrokerLimits: { spendWeekUsd: -1 } })),
    ).toBe(false);
    expect(isGatewayMutableConfig({ ...mutableConfig(), byosub: {} })).toBe(false);
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "custom-operator-ksa" }),
        "walter",
      ),
    ).toBe(true);
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "octogee-gw-walter" }),
        "walter",
      ),
    ).toBe(true);
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "octogee-gateway-walter" }),
        "walter",
      ),
    ).toBe(true);
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "octogee-gw-other" }),
        "walter",
      ),
    ).toBe(false);
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "octogee-gateway-other" }),
        "walter",
      ),
    ).toBe(false);
    for (const reserved of ["octogee-api", "octogee-glm-controller", "octogee-cron", "octogee-gateway"]) {
      expect(
        isGatewayMutableConfigForGateway(mutableConfig({ serviceAccountName: reserved }), "walter"),
      ).toBe(false);
    }
    expect(
      isGatewayMutableConfigForGateway(
        mutableConfig({ serviceAccountName: "invalid_name" }),
        "walter",
      ),
    ).toBe(false);
    expect(
      isGatewayMutableConfigForGateway(mutableConfig({ serviceAccountName: "UPPER" }), "walter"),
    ).toBe(false);
    expect(
      isGatewayMutableConfig(mutableConfig({ serviceAccount: { create: "yes" } as never })),
    ).toBe(false);
    expect(
      isGatewayMutableConfig(
        mutableConfig({ builderAccess: { kubeApiServerEgressCidrs: ["10.0.0.0/8", 1] } as never }),
      ),
    ).toBe(false);
  });

  it("reads an artifact-only selected release", async () => {
    const store = createDocumentFixtureStore({
      "gateways/walter/releases/2": {
        gatewayId: "walter",
        release: 2,
        payload: {
          imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
          imageTag: "deadbee",
        },
      },
    });

    await expect(readGatewayArtifactInStore(store, "walter", 2)).resolves.toEqual({
      imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
      imageTag: "deadbee",
    });
  });

  it("preserves immutable package receipts when projecting and cloning a release artifact", async () => {
    const openclawSourceSha = "a".repeat(40);
    const profileImages = {
      builder: {
        imageRepository:
          "us-central1-docker.pkg.dev/octogee/octogee/octogee-gateway-builder",
        imageTag: `deadbee@sha256:${"b".repeat(64)}`,
      },
    };
    const store = createDocumentFixtureStore({
      "gateways/walter/releases/2": {
        gatewayId: "walter",
        release: 2,
        payload: {
          imageRepository:
            "us-central1-docker.pkg.dev/octogee/octogee/octogee-gateway",
          imageTag: `deadbee@sha256:${"a".repeat(64)}`,
          openclawSourceSha,
          profileImages,
        },
      },
    });

    const artifact = await readGatewayArtifactInStore(store, "walter", 2);
    expect(artifact).toEqual({
      imageRepository:
        "us-central1-docker.pkg.dev/octogee/octogee/octogee-gateway",
      imageTag: `deadbee@sha256:${"a".repeat(64)}`,
      openclawSourceSha,
      profileImages,
    });
    expect(initialGatewayReleaseDocuments({
      gatewayId: "clone",
      config: mutableConfig(),
      artifact: artifact!,
      createdBy: "test",
      now: 42,
      desiredStatus: "running",
    }).releaseDoc.payload).toEqual(artifact);
  });

  it("refuses a stored release payload that still carries mutable policy", async () => {
    const store = createDocumentFixtureStore({
      "gateways/walter/releases/2": {
        gatewayId: "walter",
        release: 2,
        payload: {
          imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
          imageTag: "deadbee",
          gatewayClass: "shared",
        },
      },
    });

    await expect(readGatewayArtifactInStore(store, "walter", 2)).rejects.toBeInstanceOf(MalformedRecordError);
  });
  it("reads heartbeat telemetry from the gateway's serving runtime doc", async () => {
    const docs: Docs = {
      "glmGateways/walter": servingRuntime({ heartbeat: { status: "ready" } }),
    };

    await expect(
      readGatewayRuntimeHeartbeat(
        createDocumentFixtureStore(docs),
        durableGateway() as never,
      ),
    ).resolves.toEqual({ status: "ready" });
  });

  it("refuses a non-serving runtime even when its stale heartbeat says ready", async () => {
    const docs: Docs = {
      "glmGateways/walter": servingRuntime({
        lifecycle: "failed",
        heartbeat: { status: "ready" },
      }),
    };

    await expect(
      readGatewayRuntimeHeartbeat(
        createDocumentFixtureStore(docs),
        durableGateway() as never,
      ),
    ).resolves.toBeNull();
  });

  it("reads a hash-verified artifact from the store through the retired Mac schema upgrade", async () => {
    const payload = {
      imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
      imageTag: "deadbee",
      macOpsTokenProtocol: { version: 1 },
    };
    const store = createDocumentFixtureStore({
      "gateways/walter/releases/2": {
        gatewayId: "walter",
        release: 2,
        payloadHash: releasePayloadHash(payload as never),
        payload,
      },
    });

    await expect(readGatewayArtifactInStore(store, "walter", 2)).resolves.toEqual({
      imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
      imageTag: "deadbee",
    });
    await expect(readGatewayArtifactInStore(store, "walter", 3)).resolves.toBeNull();
    await expect(readGatewayArtifactInStore(store, "walter", null)).resolves.toBeNull();
    await expect(readGatewayArtifactInStore(store, "walter-r2", 2)).resolves.toBeNull();
  });

  it("refuses a stored release payload that still carries credential state", async () => {
    const store = createDocumentFixtureStore({
      "gateways/walter/releases/2": {
        gatewayId: "walter",
        release: 2,
        payload: {
          imageRepository: "us-central1-docker.pkg.dev/octogee/octogee/gateway",
          imageTag: "deadbee",
          byosub: { legacy: true },
        },
      },
    });

    await expect(readGatewayArtifactInStore(store, "walter", 2)).rejects.toBeInstanceOf(MalformedRecordError);
  });
});
